create type public.answer_type as enum ('player', 'club');
create type public.question_source as enum ('generated', 'manual');
create type public.question_status as enum ('draft', 'active', 'retired');

-- Reference data. A row can come from Transfermarkt, Wikidata or both, matched by ID.
create table public.players (
  id bigint generated by default as identity primary key,
  transfermarkt_id bigint unique,
  wikidata_id text unique,
  name text not null,
  -- Lower case with accents removed, written by the import so search and data agree.
  search_name text not null,
  country text,
  birth_year smallint,
  position text,
  fame_score real not null default 0,
  created_at timestamptz not null default now(),
  constraint players_have_a_source check (transfermarkt_id is not null or wikidata_id is not null)
);

create index players_search_name_trgm on public.players
  using gin (search_name extensions.gin_trgm_ops);

create table public.clubs (
  id bigint generated by default as identity primary key,
  transfermarkt_id bigint unique,
  wikidata_id text unique,
  name text not null,
  search_name text not null,
  country text,
  created_at timestamptz not null default now(),
  constraint clubs_have_a_source check (transfermarkt_id is not null or wikidata_id is not null)
);

create index clubs_search_name_trgm on public.clubs
  using gin (search_name extensions.gin_trgm_ops);

create table public.questions (
  id uuid primary key default gen_random_uuid(),
  prompt text not null,
  answer_type public.answer_type not null,
  source public.question_source not null,
  -- Which dataset the answers came from, so one source can be pulled if it proves unreliable.
  data_source text not null,
  template_key text,
  template_params jsonb not null default '{}',
  -- Stable identity for a generated question, so re-running the generator updates it in place.
  dedupe_key text not null unique,
  status public.question_status not null default 'active',
  answer_count integer not null,
  times_played integer not null default 0,
  tiers_recalculated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index questions_status_template on public.questions (status, template_key);

-- The answers and their tiers. This table must never be readable from the browser.
create table public.question_answers (
  question_id uuid not null references public.questions (id) on delete cascade,
  -- A players.id or clubs.id, depending on the question's answer_type.
  entity_id bigint not null,
  starting_tier smallint not null check (starting_tier between 1 and 7),
  current_tier smallint not null check (current_tier between 1 and 7),
  admin_tier_override smallint check (admin_tier_override between 1 and 7),
  -- The popularity the starting tier was ranked on. Breaks ties when tiers are recalculated.
  starting_popularity real not null default 0,
  times_given integer not null default 0,
  primary key (question_id, entity_id)
);

create table public.question_tags (
  question_id uuid not null references public.questions (id) on delete cascade,
  tag_type text not null check (
    tag_type in (
      'league', 'decade', 'competition', 'tournament', 'nationality', 'club', 'featured_player'
    )
  ),
  tag_value text not null,
  primary key (question_id, tag_type, tag_value)
);

create index question_tags_by_tag on public.question_tags (tag_type, tag_value);

-- Server only: row-level security is on with no policies, and the browser roles get no grants.
alter table public.players enable row level security;
alter table public.clubs enable row level security;
alter table public.questions enable row level security;
alter table public.question_answers enable row level security;
alter table public.question_tags enable row level security;

revoke all on table
  public.players,
  public.clubs,
  public.questions,
  public.question_answers,
  public.question_tags
from anon, authenticated;

/**
 * Loads a batch of generated questions with their answers and tags.
 * Safe to re-run: a question is matched on dedupe_key and updated in place,
 * and tiers that players have already reshaped are left alone.
 */
create function public.import_questions(payload jsonb)
returns integer
language plpgsql
set search_path = ''
as $$
declare
  item jsonb;
  imported_id uuid;
  crowd_tiered boolean;
  imported_count integer := 0;
begin
  for item in select value from jsonb_array_elements(payload)
  loop
    insert into public.questions (
      prompt, answer_type, source, data_source, template_key, template_params, dedupe_key, answer_count
    )
    values (
      item ->> 'prompt',
      (item ->> 'answer_type')::public.answer_type,
      'generated',
      item ->> 'data_source',
      item ->> 'template_key',
      coalesce(item -> 'template_params', '{}'::jsonb),
      item ->> 'dedupe_key',
      jsonb_array_length(item -> 'answers')
    )
    on conflict (dedupe_key) do update set
      prompt = excluded.prompt,
      data_source = excluded.data_source,
      template_params = excluded.template_params,
      answer_count = excluded.answer_count,
      updated_at = now()
    returning id, tiers_recalculated_at is not null into imported_id, crowd_tiered;

    delete from public.question_answers existing
    where existing.question_id = imported_id
      and not exists (
        select 1
        from jsonb_array_elements(item -> 'answers') answer
        where (answer ->> 'entity_id')::bigint = existing.entity_id
      );

    insert into public.question_answers (
      question_id, entity_id, starting_tier, current_tier, starting_popularity
    )
    select
      imported_id,
      (answer ->> 'entity_id')::bigint,
      (answer ->> 'tier')::smallint,
      (answer ->> 'tier')::smallint,
      (answer ->> 'popularity')::real
    from jsonb_array_elements(item -> 'answers') answer
    on conflict (question_id, entity_id) do update set
      starting_tier = excluded.starting_tier,
      starting_popularity = excluded.starting_popularity,
      current_tier = case
        when crowd_tiered then public.question_answers.current_tier
        else excluded.starting_tier
      end;

    delete from public.question_tags where question_id = imported_id;

    insert into public.question_tags (question_id, tag_type, tag_value)
    select distinct imported_id, tag ->> 'type', tag ->> 'value'
    from jsonb_array_elements(coalesce(item -> 'tags', '[]'::jsonb)) tag;

    imported_count := imported_count + 1;
  end loop;

  return imported_count;
end;
$$;

revoke execute on function public.import_questions(jsonb) from public, anon, authenticated;
